"""
Report Formatter - Phase 5
Formats reports into multiple output formats (Markdown, JSON, PDF, HTML).
"""

from typing import Dict, Any, List
from abc import ABC, abstractmethod
import json

from .report_generator import ComprehensiveReport, ReportSection, ReportFormat


class ReportFormatter(ABC):
    """Abstract base class for report formatters."""
    
    @abstractmethod
    def format(self, report: ComprehensiveReport) -> str:
        """Format report to string output."""
        pass
    
    @abstractmethod
    def get_file_extension(self) -> str:
        """Get file extension for this format."""
        pass


class MarkdownFormatter(ReportFormatter):
    """Format reports as Markdown."""
    
    def format(self, report: ComprehensiveReport) -> str:
        """Format report as Markdown."""
        output = []
        
        # Title page
        output.append(f"# {report.title}\n")
        output.append(f"**Report ID:** {report.report_id}")
        output.append(f"**Generated:** {report.generated_at.strftime('%Y-%m-%d %H:%M UTC')}")
        output.append(f"**Roadmap ID:** {report.roadmap_id}\n")
        
        if report.memory_context_id:
            output.append(f"**Memory Context:** {report.memory_context_id}\n")
        
        # Metadata
        output.append("---\n")
        output.append("## Report Metadata\n")
        output.append(f"- **Total Pages:** {report.total_pages}")
        output.append(f"- **Word Count:** {report.word_count:,}")
        output.append(f"- **Artifacts Linked:** {report.artifact_count}")
        output.append(f"- **Sections:** {len(report.sections)}\n")
        
        # Table of contents
        output.append("---\n")
        output.append("## Table of Contents\n")
        for section in report.sections:
            output.append(f"{section.number}. [{section.title}](#{section.title.lower().replace(' ', '-')})")
        output.append("\n---\n")
        
        # Sections
        for section in report.sections:
            output.append(section.content)
            output.append("\n---\n")
        
        # Footer
        output.append(f"\n*Report generated by Project Planning Service*")
        output.append(f"\n*{report.generated_at.strftime('%Y-%m-%d %H:%M UTC')}*\n")
        
        return "\n".join(output)
    
    def get_file_extension(self) -> str:
        return ".md"


class JSONFormatter(ReportFormatter):
    """Format reports as JSON."""
    
    def format(self, report: ComprehensiveReport) -> str:
        """Format report as JSON."""
        return json.dumps(report.to_dict(), indent=2, default=str)
    
    def get_file_extension(self) -> str:
        return ".json"


class HTMLFormatter(ReportFormatter):
    """Format reports as HTML."""
    
    def format(self, report: ComprehensiveReport) -> str:
        """Format report as HTML."""
        output = []
        
