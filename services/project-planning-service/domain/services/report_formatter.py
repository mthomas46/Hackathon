        output.append("<body>")
        
        # Title page
        output.append("    <div class='title-page'>")
        output.append(f"        <h1>{report.title}</h1>")
        output.append("        <div class='metadata'>")
        output.append(f"            <p><strong>Report ID:</strong> {report.report_id}</p>")
        output.append(f"            <p><strong>Generated:</strong> {report.generated_at.strftime('%Y-%m-%d %H:%M UTC')}</p>")
        output.append(f"            <p><strong>Roadmap ID:</strong> {report.roadmap_id}</p>")
        output.append("        </div>")
        output.append("    </div>")
        
        # Table of contents
        output.append("    <div class='toc'>")
        output.append("        <h2>Table of Contents</h2>")
        output.append("        <ul>")
        for section in report.sections:
            output.append(f"            <li><a href='#section-{section.number}'>{section.number}. {section.title}</a></li>")
        output.append("        </ul>")
        output.append("    </div>")
        
        # Sections
